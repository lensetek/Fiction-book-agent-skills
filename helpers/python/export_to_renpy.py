#!/usr/bin/env python3
"""
Fiction Book Agent Skills - Ren'Py Visual Novel Exporter Helper
Converts fiction manuscript markdown / dialogue into Ren'Py script (.rpy),
with definitions, ATL transforms, camera shakes, and audio cues.
"""

import os
import sys
import re
import argparse
from pathlib import Path

def sanitize_identifier(name: str) -> str:
    cleaned = re.sub(r'[^a-zA-Z0-9_]', '_', name.strip().lower())
    return re.sub(r'_+', '_', cleaned).strip('_')

def parse_markdown_to_renpy(content: str, title: str = "Visual Novel Adventure"):
    characters = set()
    bg_list = set()
    sfx_list = set()
    bgm_list = set()
    
    script_lines = []
    script_lines.append(f"# Script generated by Fiction Book Agent Skills: Ren'Py Visual Novel Exporter")
    script_lines.append(f"# Title: {title}")
    script_lines.append("")
    script_lines.append("label start:")
    script_lines.append("    # Initial scene setup")
    script_lines.append("    scene black with fade")
    
    in_choice_block = False
    
    lines = content.splitlines()
    for raw_line in lines:
        line = raw_line.strip()
        if not line:
            continue
            
        # Heading 1 or 2 as chapter / scene label
        if line.startswith("# ") or line.startswith("## "):
            heading_text = re.sub(r"^#+\s*", "", line)
            lbl = sanitize_identifier(heading_text)
            if not lbl:
                lbl = "scene_next"
            script_lines.append("")
            script_lines.append(f"    # --- {heading_text} ---")
            script_lines.append(f"    scene bg_{lbl} with dissolve")
            bg_list.add(f"bg_{lbl}")
            continue

        # Detect BGM cues [BGM: filename] or (BGM: ...)
        bgm_match = re.search(r"\[BGM:\s*([^\]]+)\]|\(BGM:\s*([^\)]+)\)", line, re.IGNORECASE)
        if bgm_match:
            track = (bgm_match.group(1) or bgm_match.group(2)).strip()
            slug = sanitize_identifier(track)
            bgm_list.add(slug)
            script_lines.append(f'    play music "audio/bgm/{slug}.ogg" fadein 2.0 loop')
            line = re.sub(r"\[BGM:\s*[^\]]+\]|\(BGM:\s*[^\)]+\)", "", line).strip()
            if not line:
                continue

        # Detect SFX cues [SFX: filename] or (SFX: ...)
        sfx_match = re.search(r"\[SFX:\s*([^\]]+)\]|\(SFX:\s*([^\)]+)\)", line, re.IGNORECASE)
        if sfx_match:
            sfx = (sfx_match.group(1) or sfx_match.group(2)).strip()
            slug = sanitize_identifier(sfx)
            sfx_list.add(slug)
            script_lines.append(f'    play sound "audio/sfx/{slug}.ogg"')
            if "guncang" in slug or "shake" in slug or "ledakan" in slug or "punch" in slug or "banting" in slug:
                script_lines.append("    with hpunch")
            line = re.sub(r"\[SFX:\s*[^\]]+\]|\(SFX:\s*[^\)]+\)", "", line).strip()
            if not line:
                continue

        # Detect Choice Menu syntax: "> Choice 1" or "- [Pilihan 1]"
        choice_match = re.match(r"^>\s*\[?Pilihan:?\s*([^\]]+)\]?|^-\s*\[([^\]]+)\]", line, re.IGNORECASE)
        if choice_match:
            choice_text = (choice_match.group(1) or choice_match.group(2)).strip()
            target_slug = sanitize_identifier(choice_text)
            if not in_choice_block:
                script_lines.append("    menu:")
                in_choice_block = True
            script_lines.append(f'        "{choice_text}":')
            script_lines.append(f"            jump {target_slug}")
            continue
        else:
            in_choice_block = False

        # Character dialogue format: "Character Name: 'Dialogue' " or "Character Name: "Dialogue""
        dialogue_match = re.match(r"^([A-Za-z0-9\s_]+)[:：]\s*(.*)$", line)
        if dialogue_match and len(dialogue_match.group(1).split()) <= 4:
            char_name = dialogue_match.group(1).strip()
            raw_text = dialogue_match.group(2).strip()
            char_tag = sanitize_identifier(char_name)
            characters.add((char_tag, char_name))
            
            # Check for emotion in parenthesis inside dialogue: (tersenyum) or (kaget)
            emotion_match = re.search(r"^\(([a-zA-Z]+)\)\s*(.*)", raw_text)
            if emotion_match:
                emotion = emotion_match.group(1).lower()
                speech = emotion_match.group(2).strip()
                speech = speech.strip('"\'“”')
                safe_speech = speech.replace('"', '\\"')
                script_lines.append(f"    show {char_tag} {emotion}")
                if emotion in ["kaget", "shock", "marah"]:
                    script_lines.append("    with vpunch")
                script_lines.append(f'    {char_tag} "{safe_speech}"')
            else:
                speech = raw_text.strip('"\'“”')
                safe_speech = speech.replace('"', '\\"')
                script_lines.append(f'    {char_tag} "{safe_speech}"')
            continue

        # Narration (regular text without speaker)
        safe_narrative = line.replace('"', '\\"')
        script_lines.append(f'    "{safe_narrative}"')

    script_lines.append("")
    script_lines.append("    # End of demo chapter")
    script_lines.append("    scene black with fade")
    script_lines.append('    "Terima kasih telah membaca/memainkan bab ini."')
    script_lines.append("    return")
    
    # Generate definitions.rpy
    color_palette = ["#3b82f6", "#ec4899", "#10b981", "#8b5cf6", "#f59e0b", "#06b6d4"]
    def_lines = [
        "# Character & Game Definitions",
        "# Generated automatically by Fiction Book Agent Skills",
        ""
    ]
    for idx, (tag, name) in enumerate(sorted(characters)):
        c_code = color_palette[idx % len(color_palette)]
        def_lines.append(f'define {tag} = Character("{name}", color="{c_code}")')
    def_lines.append('define narrator = Character(None, italic=True)')
    def_lines.append("")
    def_lines.append("# Global state variables")
    def_lines.append("default affection_score = 0")
    def_lines.append("default story_flags = {}")

    # Generate transforms.rpy
    trans_lines = [
        "# Ren'Py ATL Animation & Camera Transforms",
        "# Generated by Fiction Book Agent Skills",
        "",
        "transform lompat_kaget:",
        "    easein 0.12 yoffset -35",
        "    easeout 0.12 yoffset 0",
        "",
        "transform masuk_dari_kiri:",
        "    xalign -0.3 yalign 1.0",
        "    easein 0.35 xalign 0.15",
        "",
        "transform masuk_dari_kanan:",
        "    xalign 1.3 yalign 1.0",
        "    easein 0.35 xalign 0.85",
        "",
        "transform getar_ringan:",
        "    linear 0.05 xoffset -5",
        "    linear 0.05 xoffset 5",
        "    linear 0.05 xoffset 0",
        "",
        "transform sprite_idle:",
        "    easein 1.5 yoffset -4",
        "    easeout 1.5 yoffset 0",
        "    repeat"
    ]

    # Generate asset_manifest.md
    manifest_lines = [
        f"# Asset Manifest & Prompt Guide for '{title}'",
        "",
        "## 🖼️ Background Images Needed (1920x1080 px)",
    ]
    if bg_list:
        for bg in sorted(bg_list):
            manifest_lines.append(f"- **images/bg/{bg}.png**: Anime visual novel background, {bg.replace('_', ' ')}, detailed lighting, 1080p, makoto shinkai aesthetic.")
    else:
        manifest_lines.append("- **images/bg/bg_room.png**: Anime bedroom interior, warm afternoon sun.")

    manifest_lines.append("\n## 👤 Character Sprites Needed (Transparent PNG, ~1000x1600 px)")
    for tag, name in sorted(characters):
        manifest_lines.append(f"- **{name} (`{tag}`)**:")
        manifest_lines.append(f"  - `images/characters/{tag}_normal.png` (Ekspresi netral/senyum)")
        manifest_lines.append(f"  - `images/characters/{tag}_kaget.png` (Ekspresi kaget/terkejut)")
        manifest_lines.append(f"  - `images/characters/{tag}_marah.png` (Ekspresi emosional/tegas)")

    manifest_lines.append("\n## 🎵 Audio & BGM Cue List")
    if bgm_list:
        manifest_lines.append("### Background Music (Looping .ogg / .mp3):")
        for bgm in sorted(bgm_list):
            manifest_lines.append(f"- `audio/bgm/{bgm}.ogg` (Theme: {bgm.replace('_', ' ')})")
    if sfx_list:
        manifest_lines.append("### Sound Effects (.ogg / .wav):")
        for sfx in sorted(sfx_list):
            manifest_lines.append(f"- `audio/sfx/{sfx}.ogg` (Sound: {sfx.replace('_', ' ')})")

    return "\n".join(script_lines), "\n".join(def_lines), "\n".join(trans_lines), "\n".join(manifest_lines)

def main():
    parser = argparse.ArgumentParser(description="Export Fiction Markdown to Ren'Py Script (.rpy)")
    parser.add_argument("--input", "-i", help="Input markdown manuscript", default="chapters/chapter_01.md")
    parser.add_argument("--output-dir", "-o", help="Target output game/ directory", default="renpy_build/game")
    parser.add_argument("--title", "-t", help="Visual novel project title", default="Visual Novel Story")

    args = parser.parse_args()
    
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    
    input_file = Path(args.input)
    if input_file.exists():
        content = input_file.read_text(encoding="utf-8")
    else:
        # Default sample if file doesn't exist yet
        content = f"""# Bab 1: Pertemuan di Bawah Rinai Hujan

[BGM: tema_hujan_melankolis]
(SFX: guntur_jauh)

Malam itu, rintik hujan membasahi jendela stasiun tua yang sepi.

Arya: (kaget) "Siapa di sana? Bukankah stasiun ini sudah ditutup?"

[SFX: langkah_kaki_cepat]
Rina: (tersenyum) "Aku hanya mencari tempat berteduh. Jangan pasang wajah seram begitu."

Arya: "Tempat ini berbahaya. Ada desas-desus rumor bayangan misterius."

Rina: "Justru rumor itu yang membawaku kemari!"

- [Ajak Rina menyelidiki bersama]
- [Peringatkan Rina dan suruh pulang segera]
"""

    script_rpy, def_rpy, trans_rpy, manifest_md = parse_markdown_to_renpy(content, title=args.title)
    
    (out_dir / "script.rpy").write_text(script_rpy, encoding="utf-8")
    (out_dir / "definitions.rpy").write_text(def_rpy, encoding="utf-8")
    (out_dir / "transforms.rpy").write_text(trans_rpy, encoding="utf-8")
    (out_dir / "asset_manifest.md").write_text(manifest_md, encoding="utf-8")

    print(f"[OK] Success! Ren'Py Visual Novel files exported to: {out_dir.resolve()}")
    print("  - script.rpy")
    print("  - definitions.rpy")
    print("  - transforms.rpy")
    print("  - asset_manifest.md")

if __name__ == "__main__":
    main()
